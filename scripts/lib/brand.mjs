// Applies a brand (name, copy, colour) to the files that carry it:
//   packages/brand/brand.json          — read by the app, emails and auth
//   apps/web/src/styles/tokens.css     — the generated block between the markers
//   apps/web/assets/logos              — placeholder logos only
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { STEPS, buildPalette } from "./palette.mjs";
import { root, writePlaceholderLogos } from "./logos.mjs";

const brandFile = join(root, "packages/brand/brand.json");
const tokensFile = join(root, "apps/web/src/styles/tokens.css");

export const readBrand = () => JSON.parse(readFileSync(brandFile, "utf8"));

const writeBrand = (brand) => writeFileSync(brandFile, JSON.stringify(brand, null, 2) + "\n");

function tokensBlock({ scale, neutral }) {
  const line = (k, v) => `  ${k}: ${v};`;
  return [
    "  /* brand:start (generated by `pnpm brand`, do not edit) */",
    ...STEPS.map((s) => line(`--brand-${s}`, scale[s])),
    line("--neutral-surface", neutral.surface),
    line("--neutral-ink", neutral.ink),
    line("--neutral-ink-muted", neutral.inkMuted),
    line("--neutral-ink-muted-dark", neutral.inkMutedDark),
    line("--neutral-border", neutral.border),
    "  /* brand:end */",
  ].join("\n");
}

function writeTokens(colors) {
  const css = readFileSync(tokensFile, "utf8");
  const next = css.replace(/ *\/\* brand:start[\s\S]*?\/\* brand:end \*\//, tokensBlock(colors));
  if (next === css && !css.includes(colors.scale[600])) throw new Error("brand markers not found in tokens.css");
  writeFileSync(tokensFile, next);
}

/**
 * Update any subset of { name, tagline, description, lang, color } and
 * regenerate everything derived from it. Returns what changed on disk.
 */
export function applyBrand(changes) {
  const brand = readBrand();
  for (const key of ["name", "tagline", "description", "lang"]) {
    if (changes[key] !== undefined) brand[key] = changes[key];
  }
  if (changes.color) {
    const { seed, scale, neutral } = buildPalette(changes.color);
    brand.colors = { seed, scale, neutral };
  }
  writeBrand(brand);
  writeTokens(brand.colors);
  const logos = writePlaceholderLogos(brand.name, brand.colors.scale);
  return { brand, logos };
}
